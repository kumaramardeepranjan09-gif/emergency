"""Browser integration checks against the running local simulator."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT = Path(__file__).resolve().parents[1]

def main():
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
        context = browser.new_context(viewport={'width':1440,'height':1100}, accept_downloads=True)
        page = context.new_page()
        errors=[]
        page.on('pageerror',lambda e: errors.append(str(e)))
        page.goto('http://127.0.0.1:8080')
        expect(page.locator('#connection')).to_have_text('● SIMULATOR ONLINE')
        # Return a persisted simulator instance to a known safe state.
        page.locator('[data-scenario="normal"]').click()
        page.wait_for_timeout(1100)
        if page.locator('#resetBtn').is_enabled():
            page.locator('#resetBtn').click()
            expect(page.locator('#condition')).to_have_text('All systems within limits')
        page.locator('[data-command="M1F"]').click()
        expect(page.locator('#state1')).to_have_text('RUNNING')
        expect(page.locator('#model1')).to_have_class('model running')
        page.locator('[data-command="M2R"]').click()
        expect(page.locator('#state2')).to_have_text('RUNNING')
        page.locator('[data-scenario="warm"]').click()
        expect(page.locator('#banner')).to_have_class('banner WARNING')
        expect(page.locator('#state1')).to_have_text('RUNNING')
        page.locator('[data-scenario="hot"]').click()
        expect(page.locator('#banner')).to_have_class('banner CRITICAL')
        expect(page.locator('#state1')).to_have_text('LOCKED')
        expect(page.locator('#state2')).to_have_text('LOCKED')
        expect(page.locator('[data-command="M1F"]')).to_be_disabled()
        page.locator('#resetBtn').click()
        expect(page.locator('#toast')).to_contain_text('Reset blocked')
        page.locator('[data-scenario="normal"]').click()
        page.wait_for_timeout(1000)
        page.locator('#resetBtn').click()
        expect(page.locator('#state1')).to_have_text('STOPPED')
        page.locator('[data-command="M1F"]').click()
        page.locator('[data-scenario="motion"]').click()
        expect(page.locator('#banner')).to_have_class('banner WARNING')
        page.locator('[data-scenario="shock"]').click()
        expect(page.locator('#banner')).to_have_class('banner CRITICAL')
        page.locator('[data-scenario="normal"]').click()
        page.wait_for_timeout(1000)
        page.locator('#resetBtn').click()
        page.locator('[data-command="M2F"]').click()
        page.locator('[data-scenario="disconnect"]').click()
        expect(page.locator('#banner')).to_have_class('banner CRITICAL')
        expect(page.locator('#risk1')).to_have_text('—')
        page.locator('[data-scenario="normal"]').click()
        page.wait_for_timeout(1000)
        page.locator('#resetBtn').click()
        with page.expect_download() as dl:
            page.locator('#csvBtn').click()
        csv=Path(dl.value.path()).read_text()
        assert 'remaining1' in csv and 'simulator' in csv and 'CRITICAL' in csv
        with page.expect_download() as dl:
            page.locator('#workOrderBtn').click()
        work=Path(dl.value.path()).read_text()
        assert 'DRAFT MAINTENANCE' in work and 'SIMULATOR' in work and 'MG-002' in work
        page.evaluate('window.print=()=>window.printRequested=true')
        page.locator('#reportBtn').click()
        assert page.evaluate('window.printRequested')
        page.locator('#chartMetric').select_option('vibration')
        page.locator('#chartMetric').select_option('rotation')
        page.locator('#chartMetric').select_option('temperature')
        page.locator('[data-command="M1F"]').click()
        page.locator('[data-command="M2F"]').click()
        page.wait_for_timeout(1200)
        out=ROOT/'docs/artifacts';out.mkdir(exist_ok=True)
        page.screenshot(path=str(out/'dashboard-desktop.png'),full_page=True)
        page.pdf(path=str(out/'sample-report-simulator.pdf'),format='A4',print_background=True)
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(out/'dashboard-mobile.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile overflow'
        page.route('**/api',lambda route: route.abort())
        expect(page.locator('#connection')).to_have_text('● OFFLINE',timeout=7000)
        expect(page.locator('[data-command="M1F"]')).to_be_disabled()
        expect(page.locator('#model1')).not_to_have_class('model running')
        page.unroute('**/api')
        expect(page.locator('#connection')).to_have_text('● SIMULATOR ONLINE',timeout=7000)
        page.locator('[data-command="ALLSTOP"]').click()
        expect(page.locator('#banner')).to_have_class('banner CRITICAL')
        assert not errors, errors
        browser.close()
        print('PASS: browser commands, both 3D motors, thermal/motion/fault lockout, safe reset, CSV, work order, PDF, mobile layout and offline recovery; no JavaScript errors')
if __name__=='__main__':main()
